#!/bin/bash
# Test harness for the command guard.
# Runs commands through deny-dangerous.sh in the Claude Code payload shape and
# asserts block (exit 2) or allow. Run it after ANY edit to dangerous-patterns.txt
# or readonly-clis.txt. Must end "failed: 0".
#   bash plugins/command-guard/hooks/test-guard.sh

GUARD="$(cd "$(dirname "$0")" && pwd)/deny-dangerous.sh"
pass=0
fail=0

check() { # $1 = expected: block|allow, $2 = command string, $3 = cwd (default /tmp)
  local expected="$1" cmd="$2" cwd="${3:-/tmp}" rc verdict

  jq -cn --arg c "$cmd" --arg d "$cwd" '{tool_input:{command:$c},cwd:$d}' | "$GUARD" >/dev/null 2>&1
  rc=$?
  if [ "$rc" -eq 2 ]; then verdict="block"; else verdict="allow"; fi
  if [ "$verdict" = "$expected" ]; then
    pass=$((pass+1))
  else
    fail=$((fail+1))
    echo "FAIL expected=$expected got=$verdict : $cmd"
  fi
}

